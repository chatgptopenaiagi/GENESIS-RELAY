"""Account every selected-root entry, with explicit non-secret dispositions."""
import os,re,stat,sys
from pathlib import Path
from .common import now,run
DISPOSITIONS={'INCLUDED_EXACT','INCLUDED_TRANSFORMED','DEPENDENCY_REFERENCE','EXCLUDED_WITH_REASON','UNREADABLE_OR_MISSING'}
SECRET_NAMES={'access.json','auth.json','sessions.json','credentials.json','secrets.json','jupyter-secret.json','jupyter_cookie_secret','id_rsa','id_ed25519','id_ecdsa','.git-credentials','hosts.yml','.env','.envrc'}
CACHE_DIRS={'__pycache__','.pytest_cache','.mypy_cache','.ruff_cache','.cache'}
PATTERNS=[re.compile(p) for p in [rb'-----BEGIN (?:OPENSSH |RSA |EC )?PRIVATE KEY-----',rb'\bgh[pousr]_[A-Za-z0-9]{25,}',rb'\bsk-(?:proj-|svcacct-)?[A-Za-z0-9_-]{30,}',rb'\bAKIA[0-9A-Z]{16}\b']]

def active_secrets(root):
 values=[]
 from .common import load
 for p in [Path(root)/'private/access.json',Path(root)/'private/jupyter-secret.json']:
  data=load(p,{})
  for key in ['password','token','secret','csrf']:
   value=data.get(key)
   if isinstance(value,str) and len(value)>=8:values.append(value.encode())
 return values

def secret_match(path,values=()):
 tail=b''
 with Path(path).open('rb') as f:
  for chunk in iter(lambda:f.read(65536),b''):
   raw=tail+chunk
   if any(x in raw for x in values) or any(p.search(raw) for p in PATTERNS):return True
   tail=raw[-4096:]
 if Path(path).suffix.lower()=='.json' and Path(path).stat().st_size<2_000_000:
  from .common import load
  def contains(value):
   if isinstance(value,dict):
    for key,item in value.items():
     if re.fullmatch(r'(?i)(password|db_password|database_password|api[_-]?key|access[_-]?token|refresh[_-]?token|client[_-]?secret|private[_-]?key|csrf)',str(key)) and isinstance(item,str) and len(item)>4:return True
     if contains(item):return True
   if isinstance(value,list):return any(contains(item) for item in value)
   return False
  if contains(load(path)):return True
 return False

def classify(rel,kind):
 parts=Path(rel).parts;name=parts[-1]
 if name in SECRET_NAMES or name.startswith('.env.') or any(x in parts for x in ['.ssh','.codex','.gnupg']) or re.search(r'(?:token|password|credential|session)[-_].*\.(?:json|key|txt)$',name,re.I):return 'EXCLUDED_WITH_REASON','Authentication or private access material; recreate locally'
 if '.git' in parts:return 'DEPENDENCY_REFERENCE','Git history preserved through a verified bundle and separate worktree snapshot'
 if name.endswith(('-wal','-shm','-journal')):return 'EXCLUDED_WITH_REASON','SQLite companion; committed state captured using backup API'
 if parts[0]=='runtime':return 'EXCLUDED_WITH_REASON','Ephemeral process/cache state must not activate on another machine'
 if any(x in CACHE_DIRS for x in parts):return 'DEPENDENCY_REFERENCE','Reconstructable generated bytecode/cache, not user source'
 if name.endswith(('.pkg.tar.xz','.pkg.tar.zst','.pkg.tar.xz.sig','.pkg.tar.zst.sig','.whl')):return 'DEPENDENCY_REFERENCE','Source-platform dependency/cache artifact; not a portable environment'
 if parts[0] in {'.venv','venv','env'}:
  if kind=='directory' or kind=='symlink' or name in {'pyvenv.cfg','.gitignore','activate','activate.csh','activate.fish','Activate.ps1','python','python3','pip','pip3'} or re.match(r'^(?:python|pip)\d',name):return 'DEPENDENCY_REFERENCE','Installed environment entry represented by environment requirements'
  if any(x.endswith(('.dist-info','.egg-info')) for x in parts):return 'DEPENDENCY_REFERENCE','Installed package metadata represented in environment records'
  # Unknown files are preserved. A directory name alone never proves disposable code.
  return 'INCLUDED_EXACT','Nonstandard environment file retained as possible user source'
 if kind=='special':return 'EXCLUDED_WITH_REASON','Socket/device/FIFO cannot be safely transported as a regular file'
 if name.endswith(('.sqlite','.sqlite3','.db')) and kind=='file':return 'INCLUDED_TRANSFORMED','Consistent SQLite backup; original source remains unchanged'
 return 'INCLUDED_EXACT','Full continuation source/data/history'

def discover(source_root,*,mode='full'):
 root=Path(source_root).expanduser().resolve()
 if not root.is_dir():raise ValueError('Selected project root does not exist')
 if mode not in ['full','lightweight','offline-ready']:raise ValueError('Unknown capsule mode')
 if mode=='offline-ready':raise ValueError('OFFLINE_READY_BLOCKED: destination-compatible dependencies and offline test evidence are required')
 entries=[];errors=[];values=active_secrets(root)
 def visit(directory):
  try:children=sorted(os.scandir(directory),key=lambda x:x.name)
  except OSError as error:
   rel=Path(directory).relative_to(root).as_posix();errors.append({'path':rel,'error':type(error).__name__})
   for item in entries:
    if item['path']==rel:item.update(disposition='UNREADABLE_OR_MISSING',reason='Directory cannot be enumerated: '+type(error).__name__)
   return
  for child in children:
   path=Path(child.path);rel=path.relative_to(root).as_posix()
   try:
    s=path.lstat();kind='symlink' if stat.S_ISLNK(s.st_mode) else 'directory' if stat.S_ISDIR(s.st_mode) else 'file' if stat.S_ISREG(s.st_mode) else 'special';disposition,reason=classify(rel,kind)
    e={'root_id':'project','path':rel,'type':kind,'size':s.st_size if kind=='file' else 0,'mode':stat.S_IMODE(s.st_mode),'mtime_ns':s.st_mtime_ns,'inode':s.st_ino,'disposition':disposition,'reason':reason}
    if kind=='file' and disposition=='INCLUDED_TRANSFORMED':
     with path.open('rb') as probe:header=probe.read(16)
     if header!=b'SQLite format 3\x00':
      e.update(disposition='DEPENDENCY_REFERENCE' if re.fullmatch(r'mirror-[A-Za-z0-9_-]+\.db',path.name) else 'INCLUDED_EXACT',reason='Source package-repository metadata cache; not SQLite or a destination dependency installation' if re.fullmatch(r'mirror-[A-Za-z0-9_-]+\.db',path.name) else 'Non-SQLite file with database-like suffix retained byte-exact as opaque project evidence')
    if kind=='symlink':e['target']=os.readlink(path)
    if mode=='lightweight' and Path(rel).parts[0] in {'results','evidence','logs'}:e.update(disposition='EXCLUDED_WITH_REASON',reason='Explicit lightweight mode omits generated results/history; not full continuation')
    if kind=='file' and e['disposition'].startswith('INCLUDED') and secret_match(path,values):e.update(disposition='EXCLUDED_WITH_REASON',reason='Active-secret or credential pattern detected; source not changed',required_secret_exclusion=True)
    entries.append(e)
    if kind=='directory':visit(path)
   except OSError as error:entries.append({'root_id':'project','path':rel,'type':'unknown','size':0,'disposition':'UNREADABLE_OR_MISSING','reason':type(error).__name__});errors.append({'path':rel,'error':type(error).__name__})
 visit(root);counts={key:sum(x['disposition']==key for x in entries) for key in sorted(DISPOSITIONS)}
 code,out,err=run(['git','-C',root,'rev-parse','--show-toplevel']) if __import__('shutil').which('git') else (1,'','')
 git={'available':code==0 and Path(out.strip()).resolve()==root,'source_is_repository':code==0 and Path(out.strip()).resolve()==root}
 if git['available']:
  git['shallow']=run(['git','-C',root,'rev-parse','--is-shallow-repository'])[1].strip()=='true';git['dirty_status']=run(['git','-C',root,'status','--porcelain=v1','--untracked-files=all'])[1]
 return {'source_root':str(root),'project_id':'genesis-science-lab' if (root/'catalogue.py').is_file() and (root/'engine.py').is_file() else root.name,'project_name':root.name,'mode':mode,'observed_at':now(),'entries':entries,'counts':counts,'entry_count':len(entries),'file_count':sum(e['type']=='file' for e in entries),'bytes_total':sum(e['size'] for e in entries),'payload_estimated_bytes':sum(e['size'] for e in entries if e['disposition'].startswith('INCLUDED')),'errors':errors,'git':git,'consistency_method':'Verified idle application quiescence + SQLite backup + stable-file checks for Science Lab; bounded stability checks otherwise.'}
